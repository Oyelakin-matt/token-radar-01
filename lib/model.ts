// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every protocol that could still launch a token: no token on record, and not an
// exchange, a wrapped or staked product, a bridge, or a versioned pool. That is the house's own
// watchlist rule, applied to the whole universe instead of only the $50M floor, so the board never
// ranks a CEX, a WBTC or a staked-ETH wrapper as a launch that is coming. The watchlist's 40
// protocols are the floor; the board adds every other rankable pre-token protocol below it.
//
// Implied value is a comparable-companies model, built only from the snapshot's own figures:
//
//   comp     = median market-cap / TVL of the tokens already trading in the protocol's category
//              (at least 3 trading comps, else the whole market's median of 0.21x)
//   base     = tvl_usd x comp
//   growth   = 1 + clamp(change_7d, -50, 100) / 100 x 0.5
//   maturity = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365 days)
//   chains   = 1 + 0.04 x min(chains - 1, 5)           (wider distribution, more holders)
//   implied  = max(1, round(base x growth x maturity x chains))
//
// A lending protocol is therefore scored against lending tokens, a DEX against DEX tokens, and an
// RWA protocol against RWA tokens — not against one flat multiple for everything. No protocol name
// is ever special-cased: the same function scores every row, and the dashboard prints the comp
// table so a reader can check the arithmetic.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

